package main

import (
	"bytes"
	"os"
	"path/filepath"
	"testing"
)

// The committed reference must be what this program prints. To update it:
//
//	cd cli && go run ./cmd/gen-docs > ../docs/cli-reference.md
func TestTheCommittedReferenceIsCurrent(t *testing.T) {
	var generated bytes.Buffer
	if err := write(&generated); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join("..", "..", "..", "docs", "cli-reference.md")
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("the reference is missing: %v", err)
	}
	if !bytes.Equal(committed, generated.Bytes()) {
		t.Errorf("%s is out of date; run: cd cli && go run ./cmd/gen-docs > ../docs/cli-reference.md", path)
	}
}

func TestThePageDoesNotDependOnTheMachine(t *testing.T) {
	var first, second bytes.Buffer
	t.Setenv("SRW_API_URL", "https://x.example.com")
	t.Setenv("SRW_OUTPUT", "json")
	if err := write(&first); err != nil {
		t.Fatal(err)
	}
	t.Setenv("SRW_API_URL", "")
	t.Setenv("HOME", "/somewhere/else")
	if err := write(&second); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(first.Bytes(), second.Bytes()) {
		t.Error("the reference changes with the environment")
	}
}
